package CORE_JAVA.JAVA19_Interfaces;

public class Interface_Intro {

/*
1). Interface is used to achieve Abstraction.
2). It can use Multiple Inheritance.
3). It is used to achieve loose coupling. ( Change in one doesn't affects other's)
4). Interfaces are the blueprint of the Class.
5). Interfaces specifies what a class must do and How to do.
6). Interface will have all methods of public and abstract type.
7). All fields/variables will be public,static & Final type by default.
8). In Java-8 and above -
-default concrete methods can be defined.
-static public concrete methods can also be defined
9) In java-9 private methods can also be created.
10). Cannot create constructors in Interfaces

Syntax:-
interface I1
{
    public abstract void show();

    public static final int a=10;

    default void display()
    { // java-8 and above
    }

    static void run()   { // java-8 and above
        }

}

 */



}
